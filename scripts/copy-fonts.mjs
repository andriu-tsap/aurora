// Copies the Fontsource subsets the site uses into public/fonts with stable
// names and generates @font-face rules (with unicode-range) for layout.tsx,
// so the critical Latin files can be preloaded.
//   node scripts/copy-fonts.mjs
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(
  new URL("../apps/web/package.json", import.meta.url),
);
const faces = [
  { pkg: "@fontsource/inter", family: "Inter", weight: 400 },
  { pkg: "@fontsource/inter", family: "Inter", weight: 600 },
  { pkg: "@fontsource/space-grotesk", family: "Space Grotesk", weight: 500 },
];
const subsets = ["latin", "latin-ext", "cyrillic"];
const out = "apps/web/public/fonts";
await mkdir(out, { recursive: true });
const rules = [];
for (const face of faces) {
  const dir = path.dirname(require.resolve(`${face.pkg}/package.json`));
  const css = await readFile(path.join(dir, `${face.weight}.css`), "utf8");
  for (const block of css.split("@font-face").slice(1)) {
    const subset =
      block.match(/\/\* ([\w-]+) \*\//)?.[1] ??
      block.match(/-(latin-ext|latin|cyrillic)-/)?.[1];
    const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (
      !file ||
      !range ||
      !subsets.some((s) => file.includes(`-${s}-${face.weight}-`))
    )
      continue;
    await copyFile(path.join(dir, "files", file), path.join(out, file));
    rules.push({
      family: face.family,
      weight: face.weight,
      file,
      range: range.trim(),
      preload: file.includes("-latin-") && !file.includes("latin-ext"),
    });
    void subset;
  }
}
await writeFile(
  "apps/web/app/fonts.generated.ts",
  `// Generated by scripts/copy-fonts.mjs — do not edit by hand.
export const fontFaces = ${JSON.stringify(rules, null, 2)} as const;
`,
);
console.log(rules.map((r) => r.file).join("\n"));
